/**
 * 上下の区別が付かない目。実物と同じく数字の左下にドットを打つ。
 *
 * 対象は各桁が 6・8・9 のみで構成される数に限る（1 が入れば向きが分かるので除外）。
 * さらに180度回して別の数に読めるものだけを対象にする（並び順が逆になり 6↔9 が入れ替わる）。
 * 8・88・69・96 は回しても同じ数に読めるため曖昧さがなく、対象外。
 */
const ROTATED_DIGIT: Record<string, string> = { 6: '9', 8: '8', 9: '6' }

function isAmbiguous(n: number): boolean {
  const s = String(n)
  let rotated = ''
  for (let i = s.length - 1; i >= 0; i--) {
    const d = ROTATED_DIGIT[s[i]!]
    if (d === undefined) return false
    rotated += d
  }
  const v = Number(rotated)
  return v >= 1 && v <= 120 && v !== n
}

/** ドットを打つ目の一覧（6 9 66 68 86 89 98 99） */
export const D120_DOTTED_NUMBERS: ReadonlySet<number> = new Set(
  Array.from({ length: 120 }, (_, i) => i + 1).filter(isAmbiguous),
)
